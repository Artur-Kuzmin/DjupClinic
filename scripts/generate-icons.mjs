/**
 * Builds the site icons from the pixel mark and the colour tokens:
 *   src/app/favicon.ico     16, 32 and 48px, pixel-exact
 *   src/app/apple-icon.png  180px Apple touch icon
 *   src/app/icon.svg        scalable icon for modern browsers
 *
 * No dependencies. Run after changing the mark or the palette:
 *   node scripts/generate-icons.mjs
 * (Node 22.6+ reads the TypeScript mark file directly.)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { crc32, deflateSync } from "node:zlib";
import { MARK, MARK_SMALL } from "../src/components/pixel/mark.ts";

const root = new URL("../", import.meta.url);
const tokens = readFileSync(new URL("src/styles/tokens.css", root), "utf8");

function token(name) {
  const match = tokens.match(new RegExp(`--${name}:\\s*(#[0-9a-fA-F]{6})`));
  if (!match) throw new Error(`Token --${name} not found in tokens.css`);
  return match[1].toLowerCase();
}

const palette = { "#": token("ink"), f: token("fjord-500"), ".": token("bone-0") };
const ground = token("bone-0");

function rgb(hex) {
  return [1, 3, 5].map((i) => Number.parseInt(hex.slice(i, i + 2), 16));
}

/** Draws a grid centred on a square canvas of `size` px, `cell` px per cell. */
function raster(grid, size, cell) {
  const pixels = Buffer.alloc(size * size * 4);
  const [gr, gg, gb] = rgb(ground);
  for (let i = 0; i < size * size; i += 1) pixels.set([gr, gg, gb, 255], i * 4);
  const offset = Math.floor((size - grid.length * cell) / 2);
  grid.forEach((row, gy) => {
    [...row].forEach((char, gx) => {
      const [r, g, b] = rgb(palette[char] ?? ground);
      for (let y = 0; y < cell; y += 1) {
        for (let x = 0; x < cell; x += 1) {
          const px = offset + gx * cell + x;
          const py = offset + gy * cell + y;
          pixels.set([r, g, b, 255], (py * size + px) * 4);
        }
      }
    });
  });
  return pixels;
}

function png(size, pixels) {
  const stride = size * 4 + 1;
  const raw = Buffer.alloc(stride * size);
  for (let y = 0; y < size; y += 1) pixels.copy(raw, y * stride + 1, y * size * 4, (y + 1) * size * 4);
  const chunk = (type, data) => {
    const length = Buffer.alloc(4);
    length.writeUInt32BE(data.length);
    const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
    const crc = Buffer.alloc(4);
    crc.writeUInt32BE(crc32(body));
    return Buffer.concat([length, body, crc]);
  };
  const header = Buffer.alloc(13);
  header.writeUInt32BE(size, 0);
  header.writeUInt32BE(size, 4);
  header.set([8, 6, 0, 0, 0], 8); // 8-bit RGBA
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", header),
    chunk("IDAT", deflateSync(raw)),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

/** ICO container holding PNG-encoded images. */
function ico(images) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(images.length, 4);
  const directory = Buffer.alloc(16 * images.length);
  let offset = header.length + directory.length;
  images.forEach(({ size, data }, i) => {
    const o = i * 16;
    directory[o] = size;
    directory[o + 1] = size;
    directory.writeUInt16LE(1, o + 4);
    directory.writeUInt16LE(32, o + 6);
    directory.writeUInt32LE(data.length, o + 8);
    directory.writeUInt32LE(offset, o + 12);
    offset += data.length;
  });
  return Buffer.concat([header, directory, ...images.map((image) => image.data)]);
}

function svg(grid) {
  const n = grid.length + 2;
  const paths = {};
  grid.forEach((row, y) => {
    [...row].forEach((char, x) => {
      if (char === ".") return;
      paths[char] = `${paths[char] ?? ""}M${x + 1} ${y + 1}h1v1h-1z`;
    });
  });
  const shapes = Object.entries(paths)
    .map(([char, d]) => `  <path fill="${palette[char]}" d="${d}"/>`)
    .join("\n");
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${n} ${n}" shape-rendering="crispEdges">
  <!-- Generated by scripts/generate-icons.mjs from the pixel mark and tokens. -->
  <rect width="${n}" height="${n}" fill="${ground}"/>
${shapes}
</svg>
`;
}

const favicon = ico([
  { size: 16, data: png(16, raster(MARK_SMALL, 16, 2)) },
  { size: 32, data: png(32, raster(MARK, 32, 3)) },
  { size: 48, data: png(48, raster(MARK, 48, 4)) },
]);

writeFileSync(new URL("src/app/favicon.ico", root), favicon);
writeFileSync(new URL("src/app/apple-icon.png", root), png(180, raster(MARK, 180, 14)));
writeFileSync(new URL("src/app/icon.svg", root), svg(MARK));
console.log("Icons written: favicon.ico, apple-icon.png, icon.svg");
